function normalizeLanguage(language, fallback = DEFAULT_LANGUAGE) {
  const normalized = String(language || "").trim().toLowerCase();
  return SUPPORTED_LANGUAGES.some((entry) => entry.code === normalized)
    ? normalized
    : fallback;
}

function resolveMessage(language, key) {
  const safeLanguage = normalizeLanguage(language);
  return key.split(".").reduce((value, segment) => {
    if (value && Object.prototype.hasOwnProperty.call(value, segment)) {
      return value[segment];
    }
    return undefined;
  }, MESSAGES[safeLanguage]);
}

function interpolate(template, variables = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_match, key) => {
    const value = variables[key];
    return value === undefined || value === null ? "" : String(value);
  });
}

function buildTranslator(language) {
  const safeLanguage = normalizeLanguage(language);
  return (key, variables = {}) => {
    const resolved = resolveMessage(safeLanguage, key);
    if (typeof resolved === "string") {
      return interpolate(resolved, variables);
    }
    return key;
  };
}

function getLanguageOptions(language) {
  const safeLanguage = normalizeLanguage(language);
  return SUPPORTED_LANGUAGES.map((entry) => ({
    code: entry.code,
    label: resolveMessage(safeLanguage, `languages.${entry.code}`) || entry.nativeLabel,
  }));
}

